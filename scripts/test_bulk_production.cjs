// Writes only to a disposable local QA fixture (tools/bulk-production-qa).
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const output=path.resolve('tools/bulk-production-qa');
const fixture=JSON.parse(fs.readFileSync(path.join(output,'fixture.json'),'utf8'));
const base=process.env.BULK_QA_BASE||'http://127.0.0.1:8034';
assert.match(base,/^http:\/\/127\.0\.0\.1:\d+$/);
const delay=ms=>new Promise(r=>setTimeout(r,ms));
(async()=>{
  const targets=await fetch('http://127.0.0.1:9344/json/list').then(r=>r.json());
  const ws=new WebSocket(targets.find(t=>t.type==='page').webSocketDebuggerUrl);
  await new Promise((resolve,reject)=>{ws.onopen=resolve;ws.onerror=reject;});
  let next=0; const pending=new Map(),errors=[],checks=[];
  ws.onmessage=({data})=>{const m=JSON.parse(data);if(m.id){const p=pending.get(m.id);pending.delete(m.id);m.error?p.reject(m.error):p.resolve(m.result);}if(m.method==='Runtime.exceptionThrown')errors.push(m.params.exceptionDetails);};
  const call=(method,params={})=>new Promise((resolve,reject)=>{const id=++next;pending.set(id,{resolve,reject});ws.send(JSON.stringify({id,method,params}));});
  const run=async expression=>{const r=await call('Runtime.evaluate',{expression,awaitPromise:true,returnByValue:true});if(r.exceptionDetails)throw Error(JSON.stringify(r.exceptionDetails));return r.result.value;};
  const wait=async expression=>{for(let n=0;n<150;n++){if(await run(expression))return;await delay(100);}throw Error('Timeout '+expression+' '+await run('document.body.innerText.slice(-3500)'));};
  const shot=async name=>{await delay(250);const r=await call('Page.captureScreenshot',{format:'png',captureBeyondViewport:false});fs.writeFileSync(path.join(output,name),Buffer.from(r.data,'base64'));};
  const usageCount=()=>run(`ProductionApiPage.get('/batches/${fixture.batch_id}/').then(r=>r.usages.length)`);
  try {
    await call('Runtime.enable');await call('Page.enable');
    await call('Emulation.setDeviceMetricsOverride',{width:1600,height:1100,deviceScaleFactor:1,mobile:false});
    await call('Page.navigate',{url:base});
    await wait("typeof App!=='undefined' && document.getElementById('pageContainer')");
    await run("App.navigate('production-batches')");
    await wait("ProductionApiPage.staff.length>0 && document.getElementById('prodDetail')");
    await run(`ProductionApiPage.s.staffId='${fixture.staff_id}';ProductionApiPage.select(${fixture.batch_id})`);
    await wait(`ProductionApiPage.detail?.id===${fixture.batch_id} && document.querySelector('#prodUsages')`);
    assert.match(await run('ProductionApiPage.detail.item.name'),/QA 일괄 투입 18원료/);
    assert.equal(await usageCount(),3);
    await run('ProductionApiPage.prepareBulkUse()');
    await wait('ProductionApiPage.bulkUse?.rows.length===15 && !ProductionApiPage.busy');
    assert.equal(await usageCount(),3);
    assert.equal(await run('ProductionApiPage.bulkErrors().length'),0);
    assert.equal(await run('document.querySelectorAll("#prodUsages table").length'),2); // existing records + draft, no duplicate BOM table
    checks.push('18 BOM ingredients: keeps 3 existing usages, drafts only remaining 15; preview makes no writes');
    await run("(()=>{const input=document.querySelector('#prodBulkUse input[aria-label$=\"이번 실제 투입량\"]');input.value='100';input.dispatchEvent(new Event('input',{bubbles:true}));})()");
    assert.equal(await run("document.getElementById('prodBulkSave').disabled"),true);
    await run('ProductionApiPage.prepareBulkUse(true)');
    await wait('!ProductionApiPage.busy');
    assert.equal(await run('ProductionApiPage.bulkUse.rows[0].shortfall'),'90');
    assert.match(await run("document.getElementById('prodBulkUse').innerText"),/부족 90/);
    assert.equal(await usageCount(),3);
    await run("ProductionApiPage.editBulk(0,'quantity','0.02');ProductionApiPage.prepareBulkUse(true)");
    await wait('!ProductionApiPage.busy');
    assert.equal(await run('ProductionApiPage.bulkErrors().length'),0);
    const firstLot=await run('ProductionApiPage.bulkUse.rows[0].choices[0].lot_id');
    await run(`ProductionApiPage.editBulkLot(0,${firstLot},'0.01')`);
    assert.equal(await run("document.getElementById('prodBulkSave').disabled"),true);
    await run(`ProductionApiPage.editBulkLot(0,${firstLot},'0.02');ProductionApiPage.editBulk(14,'selected',false)`);
    assert.equal(await run('ProductionApiPage.bulkErrors().length'),0);
    checks.push('quantity edit, shortage, manual LOT total mismatch, corrected allocation, selection');
    await run("document.getElementById('prodBulkUse').scrollIntoView({block:'start'})");
    await shot('bulk-production-desktop.png');
    await call('Emulation.setDeviceMetricsOverride',{width:800,height:1100,deviceScaleFactor:1,mobile:false});
    assert.equal(await run('document.documentElement.scrollWidth<=innerWidth'),true);
    await shot('bulk-production-tablet.png');
    await call('Emulation.setDeviceMetricsOverride',{width:1600,height:1100,deviceScaleFactor:1,mobile:false});
    // Commit succeeds but the response is lost: retry must keep the payload and key.
    await run("window.qaOriginalPost=ProductionApiPage.post;ProductionApiPage.post=async function(p,b){const result=await window.qaOriginalPost.call(this,p,b);if(p.endsWith('/usages/'))throw Error('QA: 저장 후 응답 유실');return result;};ProductionApiPage.saveBulkUse()");
    await wait('!ProductionApiPage.busy && ProductionApiPage.bulkUse?.submitted');
    assert.equal(await usageCount(),17);
    assert.equal(await run("document.querySelector('#prodBulkUse fieldset').disabled"),true);
    await run('ProductionApiPage.post=window.qaOriginalPost;ProductionApiPage.saveBulkUse()');
    await wait('!ProductionApiPage.busy && !ProductionApiPage.bulkUse && ProductionApiPage.detail.usages.length===17');
    assert.equal(await usageCount(),17);
    await run('ProductionApiPage.prepareBulkUse()');
    await wait('!ProductionApiPage.busy && ProductionApiPage.bulkUse?.rows.length===1');
    await run('ProductionApiPage.saveBulkUse()');
    await wait('!ProductionApiPage.busy && ProductionApiPage.detail.usages.length===18');
    await run('ProductionApiPage.prepareBulkUse()');
    await wait('!ProductionApiPage.busy && ProductionApiPage.bulkUse?.rows.length===0');
    assert.equal(await usageCount(),18);
    assert.equal(await run(`ProductionApiPage.get('/lots/${firstLot}/').then(r=>r.quantity)`),'9.98');
    checks.push('selected 14 ingredients saved atomically; lost response replay adds no duplicates; final remaining 1 saved; completed rows excluded; actual quantity reflected in stock');
    assert.deepEqual(errors,[]);
    fs.writeFileSync(path.join(output,'report.json'),JSON.stringify({passed:true,checks,errors},null,2));
    console.log(JSON.stringify({passed:true,checks}));
  } finally {ws.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
