// Local browser QA only. Requires an isolated, seeded QA DB and Chrome CDP.
// Never point the default browser test at the hosted QA site.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const base = 'http://127.0.0.1:8018';
const output = path.resolve('tools/qa-ui-results');
fs.mkdirSync(output, {recursive:true});
const delay = ms => new Promise(r=>setTimeout(r,ms));
(async()=>{
  const targets=await fetch('http://127.0.0.1:9337/json/list').then(r=>r.json());
  const target=targets.find(t=>t.type==='page' && (t.url==='about:blank' || t.url.startsWith(base)));
  assert(target,'Start a dedicated headless Chrome with CDP port 9337.');
  const ws=new WebSocket(target.webSocketDebuggerUrl);
  await new Promise((resolve,reject)=>{ws.onopen=resolve;ws.onerror=reject;});
  let next=0;
  const pending=new Map(), errors=[];
  ws.onmessage=({data})=>{
    const m=JSON.parse(data);
    if(m.id) { const p=pending.get(m.id); if(p) {pending.delete(m.id); m.error?p.reject(m.error):p.resolve(m.result);} }
    if(m.method==='Runtime.exceptionThrown') errors.push(m.params.exceptionDetails);
  };
  const call=(method,params={})=>new Promise((resolve,reject)=>{const id=++next;pending.set(id,{resolve,reject});ws.send(JSON.stringify({id,method,params}));});
  const run=async expression=>{
    const r=await call('Runtime.evaluate',{expression,awaitPromise:true,returnByValue:true});
    if(r.exceptionDetails) throw new Error(JSON.stringify(r.exceptionDetails));
    return r.result.value;
  };
  const wait=async expression=>{
    for(let i=0;i<100;i++) {if(await run(expression)) return;await delay(100);}
    throw new Error('Timed out: '+expression+'\n'+await run('document.body.innerText.slice(-4000)'));
  };
  const click=selector=>run(`document.querySelector(${JSON.stringify(selector)}).click()`);
  const fill=(selector,value,event='input')=>run(`(()=>{const el=document.querySelector(${JSON.stringify(selector)});el.value=${JSON.stringify(value)};el.dispatchEvent(new Event(${JSON.stringify(event)},{bubbles:true}));})()`);
  const screenshot=async name=>{await run("document.getElementById('toastContainer')?.replaceChildren()");await delay(450);const r=await call('Page.captureScreenshot',{format:'png',captureBeyondViewport:false});fs.writeFileSync(path.join(output,name+'.png'),Buffer.from(r.data,'base64'));};
  try {
    await call('Runtime.enable'); await call('Page.enable');
    await call('Emulation.setDeviceMetricsOverride',{width:1440,height:1000,deviceScaleFactor:1,mobile:false});
    await call('Page.navigate',{url:base});
    await wait("typeof App!=='undefined' && document.getElementById('pageContainer')");
    await run("App.navigate('production-batches')");
    await wait("document.querySelector('#prodCreate [name=item_id] option[value]') && ProductionApiPage.semiItems.length>0");
    const items=await run('ProductionApiPage.semiItems.map(i=>({id:i.id,name:i.name,code:i.item_code}))');
    const product=items.find(i=>i.name==='녹용분말');
    assert(product,'QA fixture must include 녹용분말');
    await fill('#prodCreate [name=item_id]',String(product.id),'change');
    await fill('#prodCreate [name=planned_quantity]','1');
    await wait("document.querySelector('#prodPlanPreview table')");
    assert.match(await run("document.querySelector('#prodPlanPreview').innerText"),/녹용/);
    assert.equal(await run("document.querySelector('#prodApiPage .prod-layout').classList.contains('creating')"),true);
    await screenshot('production-plan');
    const before=await run("fetch('/api/v1/inventory/batches/').then(r=>r.json()).then(r=>r.count)");
    assert.equal(before,0,'Run against a fresh isolated prepare-stage DB.');
    await click('#prodCreateSubmit');
    await wait("document.getElementById('prodStartBtn') && !ProductionApiPage.busy");
    assert.equal(await run('ProductionApiPage.detail.status'),'PLANNED');
    await click('#prodStartBtn');
    await wait("ProductionApiPage.detail.status==='IN_PROGRESS' && !ProductionApiPage.busy");
    await click('#prodUsages button[onclick*=pickBomLine]');
    await wait("ProductionApiPage.fefo && !ProductionApiPage.busy");
    assert.equal(await run('ProductionApiPage.allocationTotal()'),'1');
    assert.equal(await run("document.querySelector('#prodUseForm details').open"),false);
    assert.equal(await run("!!document.querySelector('#prodUseForm input[type=search]')"),false);
    await screenshot('production-allocation');
    await run("document.querySelector('#prodUseForm details').open=true");
    const first=await run("document.querySelector('#prodUseForm [data-pick]:checked').dataset.pick");
    await fill(`#prodUseForm [data-amount="${first}"]`,'0.5');
    assert.equal(await run("document.getElementById('prodUseBtn').disabled"),true);
    await fill(`#prodUseForm [data-amount="${first}"]`,'1');
    assert.equal(await run("document.getElementById('prodUseBtn').disabled"),false);
    await click('#prodUseBtn');
    await wait("ProductionApiPage.detail.usages.length>0 && !ProductionApiPage.busy");
    await fill('#prodOutputForm [name=output_quantity]','1');
    await click('#prodOutputBtn');
    await wait("ProductionApiPage.detail.outputs.length>0 && !ProductionApiPage.busy");
    await click('#prodCompleteBtn');
    await wait("ProductionApiPage.detail.status==='COMPLETED' && !ProductionApiPage.busy");
    await run("ProductionApiPage.detailTab('documents')");
    await wait("document.getElementById('prodCcpOk')");
    await run("ProductionApiPage.detailTab('trace')");
    await wait("document.querySelector('.prod-trace-lot')");
    await screenshot('production-trace');
    await run("App.navigate('raw-materials')");
    await wait("document.getElementById('invLedgerTable')");
    assert.equal(await run('InventoryApiPage.state().tab'),'ledger');
    assert.equal(await run("!!document.querySelector('.inv-overview')"),false);
    assert.equal(await run("document.querySelector('#invApiPage .tabs').innerText.includes('현재고')"),true);
    await click('[data-period="today"]');
    await wait("InventoryApiPage.cache?.tab==='ledger'");
    assert.equal(await run("document.querySelector('[data-period=today]').getAttribute('aria-pressed')"),'true');
    await fill('#invFrom','2026-10-01','change');
    await wait("InventoryApiPage.cache?.tab==='ledger'");
    assert.equal(await run("document.querySelectorAll('[data-period][aria-pressed=true]').length"),0);
    await click('[data-period="month"]');
    await wait("InventoryApiPage.cache?.tab==='ledger'");
    await fill('#invSearch','녹용');
    await wait("InventoryApiPage.cache && InventoryApiPage.cache.data.results.length>0 && InventoryApiPage.cache.data.results.every(i=>i.item.name.includes('녹용'))");
    await run("InventoryApiPage.set('direction','OUT')");
    await wait("InventoryApiPage.cache && document.querySelectorAll('#invLedgerTable tbody tr[data-movement]').length>0");
    assert.equal(await run("InventoryApiPage.ledgerLines(InventoryApiPage.cache.data).every(r=>r.line.quantity.startsWith('-'))"),true);
    // Inspect the actual Excel payload for the same filtered rows as the table.
    await run("window.qaOriginalDownload=XlsxWriter.download; XlsxWriter.download=(name,sheets)=>{window.qaExport={name,sheets};};InventoryApiPage.exportExcel()");
    assert.equal(await run('window.qaExport.sheets[0].rows.length'),1);
    assert.equal(await run("window.qaExport.sheets[0].rows[0][2].includes('녹용')"),true);
    await screenshot('inventory-ledger');
    await run("XlsxWriter.download=window.qaOriginalDownload;InventoryApiPage.set('tab','stock')");
    await wait("InventoryApiPage.cache?.tab==='stock'");
    assert.equal(await run("document.querySelectorAll('#invStockTable tbody tr').length"),await run('InventoryApiPage.cache.data.results.length'));
    await click('#invStockTable tbody button');
    await wait("document.querySelector('#modalContainer [data-stock-lot]')");
    assert.equal(await run("document.getElementById('modalContainer').classList.contains('inventory-detail-modal')"),true);
    await click('#modalContainer [data-stock-lot]');
    await run('InventoryApiPage.applyDetailSelection()');
    await wait("InventoryApiPage.cache?.tab==='ledger'");
    assert.equal(await run('!!InventoryApiPage.state().selectedLot'),true);
    assert.match(await run("document.querySelector('#invApiContent').innerText"),/LOT/);
    await run("InventoryApiPage.openQaReceipt()");
    await wait("document.getElementById('qaReceiptItem')");
    assert.equal(await run("document.getElementById('modalContainer').classList.contains('inventory-detail-modal')"),false);
    assert.equal(await run("[...document.getElementById('qaReceiptItem').options].every(o=>o.textContent.startsWith('[원료]'))"),true);
    await fill('#qaReceiptSearch','녹용');
    assert.equal(await run("[...document.getElementById('qaReceiptItem').options].every(o=>o.textContent.includes('녹용'))"),true);
    const receiptItem=await run("[...document.getElementById('qaReceiptItem').options].find(o=>o.textContent.includes('1000004')).value");
    await fill('#qaReceiptItem',receiptItem,'change');
    await fill('#qaReceiptUnit','g','change');
    await fill('#qaReceiptForm [name=quantity]','500');
    await fill('#qaReceiptForm [name=expiration_status]','NONE','change');
    await fill('#qaReceiptForm [name=judgment]','PASS','change');
    await screenshot('receipt');
    await click('#qaReceiptSave');
    await wait("!document.getElementById('modalContainer').classList.contains('active')");
    const latest=await run(`fetch('/api/v1/inventory/receipts/?item_id='+${JSON.stringify(receiptItem)}).then(r=>r.json()).then(r=>r.results[0])`);
    assert.equal(latest.quantity,'0.5','Receipt entry g -> kg must save exactly.');
    await run("InventoryApiPage.set('tab','stock')");
    await wait("InventoryApiPage.cache?.tab==='stock'");
    await screenshot('inventory-stock');
    await call('Emulation.setDeviceMetricsOverride',{width:820,height:1180,deviceScaleFactor:1,mobile:false});
    await run("App.navigate('production-batches');ProductionApiPage.openCreate()");
    await wait("document.querySelector('#prodCreate [name=item_id]')");
    await screenshot('production-tablet');
    assert.equal(await run('document.documentElement.scrollWidth>window.innerWidth'),false,'No horizontal page overflow at tablet width.');
    await call('Emulation.setDeviceMetricsOverride',{width:1440,height:1000,deviceScaleFactor:1,mobile:false});
    assert.equal(errors.length,0,JSON.stringify(errors));
    fs.writeFileSync(path.join(output,'report.json'),JSON.stringify({passed:true,checks:['plan preview','plan/start separation','allocation and total validation','production completion and CCP','inventory filters and Excel','shared item detail','LOT selection applied to ledger','receipt g-to-kg','stock totals','tablet layout'],errors},null,2));
    console.log('Browser QA passed. Screenshots and report:',output);
  } finally {ws.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
