// Exact mass conversion and CSV validation without touching any workbook or business DB.
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const context=vm.createContext({console,URLSearchParams,document:{},window:{},App:{},setTimeout:()=>{}});
const root='frontend/static/prototype/js/modules/';
vm.runInContext(fs.readFileSync(root+'mass-units.js','utf8')+'\nthis.mass=MassUnits;',context);
vm.runInContext(fs.readFileSync(root+'inventory-api.js','utf8')+'\nthis.inventory=InventoryApiPage;',context);
vm.runInContext(fs.readFileSync(root+'inventory-manage.js','utf8')+'\nthis.manage=InventoryManage;',context);
const {mass,inventory,manage}=context;
assert.equal(mass.convert('0.000001','kg','g'),'0.001');
assert.equal(mass.convert('500','g','kg',true),'0.5');
assert.equal(mass.convert('9007199254740992.000001','kg','g'),'9007199254740992000.001');
assert.equal(mass.convert('-0.125','kg','g'),'-125');
assert.equal(mass.convert('1000.000','g','kg',true),'1');
assert.throws(()=>mass.convert('0.0001','g','kg',true),/6/);
assert.throws(()=>mass.convert('1e3','g','kg'),/숫자/);
assert.throws(()=>mass.convert('1','EA','kg'),/단위/);
assert.equal(inventory.defaultExpiration('2026-10-21'),'2027-10-20');
assert.equal(inventory.defaultExpiration('2024-02-29'),'2025-02-27');
assert.equal(inventory.defaultExpiration('2027-03-01'),'2028-02-29');
inventory.detailContext={balance:'positive',expiry:'valid'};
assert.equal(inventory.detailLotVisible({quantity:'1',expiration_status:'KNOWN',is_expired:false}),true);
assert.equal(inventory.detailLotVisible({quantity:'0',expiration_status:'KNOWN',is_expired:false}),false);
assert.equal(inventory.detailLotVisible({quantity:'1',expiration_status:'KNOWN',is_expired:true}),false);
const rows=manage.parseCsv('\uFEFFitem_code,supplier_code,received_date,quantity,note\r\nA,V,2026-10-21,1,"줄1\n줄2, 따옴표 ""검사"""\r\n');
assert.equal(rows.length,1);
assert.equal(rows[0].note,'줄1\n줄2, 따옴표 "검사"');
assert.throws(()=>manage.parseCsv('item_code,quantity\nA,1'),/supplier_code/);
assert.throws(()=>manage.parseCsv('item_code,supplier_code,received_date,quantity\nA,V,2026-10-21'),/열 수/);
console.log('Inventory feedback checks passed: exact kg/g, EA separation, expiration, LOT filters, CSV.');
